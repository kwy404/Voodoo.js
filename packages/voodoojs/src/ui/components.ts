/**
 * Interpret a boolean attribute. Accepts the short form (`<VButton loading>`),
 * text form (`loading="true"`), and reactive binding (`:loading="saving"`).
 */
function flag(value: unknown): boolean {
  if (value === true) return true;
  if (value === false || value === null || value === undefined) return false;
  if (typeof value === 'number') return value !== 0;
  const text = String(value).trim().toLowerCase();
  return text === '' || text === 'true' || text === '1' || text === 'yes';
}

/** Generate `isX` computed properties from the provided boolean props. */
function flags(...names: string[]): Record<string, (this: any) => boolean> {
  const out: Record<string, (this: any) => boolean> = {};
  for (const name of names) {
    const key = `is${name.charAt(0).toUpperCase()}${name.slice(1)}`;
    out[key] = function (this: any): boolean {
      return flag(this[name]);
    };
  }
  return out;
}

