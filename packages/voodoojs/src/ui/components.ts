/**
 * Resolve an attribute that can be a variable name from outer scope,
 * JSON, or a comma-separated list.
 *
 * ```html
 * <VSelect options="states" />          <!-- variable from surrounding v-data -->
 * <VSelect options="CA, TX, NY" />      <!-- literal list -->
 * <VSelect :options="loadedList" />     <!-- reactive binding -->
 * ```
 */
function fromOuterScope(instance: any, raw: unknown): unknown {
  if (raw == null || typeof raw !== 'string') return raw;
  const text = raw.trim();
  if (!text) return null;

  if (text.startsWith('[') || text.startsWith('{')) {
    try {
      return JSON.parse(text);
    } catch {
      return null;
    }
  }

  const head = text.split(/[.[(]/)[0].trim();
  if (!/^[A-Za-z_$][\w$]*$/.test(head)) return null;

  const parent = instance.$scope?.parent;
  if (!parent || !parent.has(head)) return null;
  return evaluateIn(text, parent, 'list attribute');
}

/** Break a list written in an attribute, respecting spaces. */
function splitList(text: string): string[] {
  return String(text)
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean);
}

/** Make the host element respond as a native field, for `v-model`. */
function hostModel(instance: any, model: { get(): unknown; set(value: unknown): void }): void {
  const el = instance.$el as HTMLElement;
  Object.defineProperty(el, 'value', {
    configurable: true,
    enumerable: false,
    get: model.get,
    set: model.set,
  });
}

/** Notify the host's `v-model` that the value changed. */
function notify(el: HTMLElement): void {
  el.dispatchEvent(new Event('input', { bubbles: true }));
  el.dispatchEvent(new Event('change', { bubbles: true }));
}

