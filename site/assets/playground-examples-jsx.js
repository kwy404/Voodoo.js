/**
 * The Tailwind-styled JSX examples the playground loads, in English.
 *
 * Same entry shape as playground-examples.js — a stable id, the group it sits
 * under, a short title, a one-line explanation and the code as an array of
 * lines — so these merge into that array without any reshaping. They are
 * exposed separately as window.VOODOO_PLAYGROUND_EXAMPLES_JSX only so the two
 * files can be edited independently.
 *
 * Every id is prefixed jsx-tw- so it cannot collide with an existing one.
 *
 * WHY TAILWIND IS SPELLED OUT IN FULL HERE
 *
 * These samples exist to show that real JSX in a plain .html file survives
 * contact with a real design system. Two-utility class attributes would not
 * prove anything, so the classes are the ones you would actually ship: spacing
 * rhythm, type hierarchy, hover and focus states, ring offsets, tabular
 * numerals. The preview loads Tailwind from the play CDN.
 *
 * THREE RULES EVERY SAMPLE BELOW OBEYS, LEARNED THE HARD WAY
 *
 * 1. Dynamic styling goes through `:class` and `:style`, never through braces
 *    inside a plain attribute. A plain `class="bg-{tone}-600"` is left exactly
 *    as typed — only `v-*`, `:` and `@` attributes are expressions — and the
 *    unquoted JSX form `style={{ ... }}` cannot work at all, because an
 *    unquoted HTML attribute value ends at the first space and attribute names
 *    are lowercased, both before a single line of script has run.
 *
 * 2. No `v-if` on an element that WRAPS a JSX region. `v-if` takes its element
 *    out of the document and re-clones it on every change, so the region's
 *    anchor ends up in the detached copy and nothing ever renders into the live
 *    one. `v-if` inside a template — on a badge in a row, say — is fine, because
 *    each clone is walked on its own. `v-show` is fine anywhere, since it only
 *    toggles display.
 *
 * 3. Inside a table, keep empty `()` out of the expression text. The HTML
 *    parser foster-parents the loose text out of `<tbody>` and the recovery
 *    matches each empty `()` left behind against a row in the table, so a
 *    stray no-argument call such as `rows.slice()` in the same expression
 *    throws the count off and the region is declined. `[...rows].sort(...)`
 *    does the same job with no empty parentheses.
 *
 * 4. One element-spanning region per parent element, and it has to be the
 *    first `{` in its own text node. The scanner walks a parent's children in
 *    order and a claimed region takes its nodes out of the document, so the
 *    sibling it would have continued from no longer has a next sibling and
 *    everything after it in that parent goes unvisited. Two regions written
 *    side by side rendered the first and left the second on screen as literal
 *    text, and a conditional badge written above a nested `map` silently cost
 *    that map its list. The fix is a wrapper element per region, and where the
 *    layout cannot afford an extra box the wrapper is `class="contents"`, which
 *    is `display: contents` — the children stay flex or grid items of the real
 *    parent and an empty wrapper takes no space at all. Ordinary `{ value }`
 *    interpolation is unaffected: the core renderer handles that on its own
 *    pass and never depends on this walk.
 */

